    // ---- (j) start clamp and end clamp

    @Test
    fun j_theFirstFramesCaptureResultWithAnOlderMonoValueLandsInBucketZeroAndTheEndSideInTheLastPartialBucket() {
        val start = 5_000_000_000L
        // the first frame's capture result was converted before anything was estimated (offset 0); from the first analyzer
        // frame on the estimator's provisional offset (30 ms) applies to both paths
        val s = Session(start, null, frame24, crOffsetNs = 30_000_000L, frameOffsetNs = 30_000_000L)
        val raws = (0 until 48).map { start + it * frame24 }
        assertEquals(FrameScheduler.CaptureDecision.PENDING, s.scheduler.onCaptureResult(CameraStamp(start, start)))
