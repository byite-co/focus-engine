    // ---- (d) a 500 ms capture gap: catch-up keeps the phase

    @Test
    fun d_afterACaptureGapTheCatchUpKeepsTheTargetPhase() {
        val start = 5_000_000_000L
        val s = Session(start, period15, frame24)
        val before = (0 until 48).map { start + (it * frame24) } // 2 s at 24 fps
        for (r in before) s.both(r)
        val lastBefore = s.filledRaw.last()
        val gapNs = 500_000_000L
        val resume = before.last() + frame24 + gapNs
        val after = (0 until 480).map { resume + it * frame24 } // 20 s: the 41.7 / 83.3 alternation averages out
        for (r in after) s.both(r)
        val anchor = s.scheduler.anchorRawTs!!
        assertEquals(start, anchor)
        assertEquals(0L, (s.scheduler.nextDueRawTs - anchor) % period15, "next_due stays on the anchor phase after the catch-up")
        val filledAfter = s.filledRaw.filter { it > lastBefore }
        assertTrue(filledAfter.size > 2)
        assertEquals(resume, filledAfter.first(), "the first frame after the gap fills the slot that was due during the gap")
        for (f in filledAfter.drop(1)) {
            val phase = (f - anchor) % period15
            val dist = minOf(phase, period15 - phase)
            assertTrue(dist <= frame24 / 2 + 1, "frame $f after the gap is ${dist / 1e6} ms from a slot target: the phase slipped")
        }
        val steady = filledAfter.drop(1)
        val afterRate = (steady.size - 1) / ((steady.last() - steady.first()) / 1e9)
        assertTrue(abs(afterRate - 15.0) < 0.05, "rate after the gap $afterRate Hz")
        // re-anchoring to the resumed frame (the rejected design, 정정 3) would have put every later slot 33 ms off this phase
        assertTrue(((resume - anchor) % period15).let { minOf(it, period15 - it) } > frame24 / 2, "the resumed frame itself is off-phase, so the check above is meaningful")
        assertEquals(0L, s.scheduler.slotsMissed, "a capture gap is a gap, not a missed slot: no frame was selected during it")
        // the gap itself is visible as a long gap in the aggregator (period 66.7 ms → long threshold 300 ms)
        val closed = s.closeAll(s.startMonoMs + 30_000)
        assertEquals(1, closed.sumOf { it.second.gapsOverLongThreshold })
    }

