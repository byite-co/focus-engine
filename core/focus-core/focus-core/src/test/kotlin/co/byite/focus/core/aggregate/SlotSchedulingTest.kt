/**
 * Directive E 9장 (a)~(o): the selected timestamp lists are generated by the production [FrameScheduler] and counted by
 * the production [FeatureAggregator], [StopSequence] and [V0bReport]. The harness below is the analysis-thread glue
 * of `CameraPipeline.analyze` reduced to its counter calls: capture result → scheduler, analyzer frame → scheduler →
 * (skip | Face outcome), in the order the events reach the analysis thread. Every time is raw camera ns; the mono
 * conversion is a per-path offset so UNKNOWN-source devices (two conversion paths, different offsets) can be modelled.
 */
private val device = DeviceSample(thermalStatus = 0, isInteractive = false, isDeviceIdle = false, screenState = ScreenState.OFF, appState = AppState.BACKGROUND)

class SlotSchedulingTest {

    private fun ms(x: Double): Long = (x * 1_000_000.0).roundToLong()

    /** Nominal camera frame interval and Face period in ns. */
    private val frame24 = GapThresholds.frameIntervalNs(24)
    private val period15 = GapThresholds.periodNs(15.0)
    private val period12 = GapThresholds.periodNs(12.0)

    /**
     * Session harness: raw camera timestamps, two offsets (capture results are converted with [crOffsetNs], analyzer
     * frames with [frameOffsetNs] — 0/0 models a REALTIME camera), the production scheduler and aggregator.
     */
    private class Session(
        val startRaw: Long,
        processPeriodNs: Long?,
        frameIntervalNs: Long,
        val crOffsetNs: Long = 0L,
        val frameOffsetNs: Long = 0L,
        sink: (FeatureAggregator) -> CameraCounterSink = { it },
        gapNs: Long = GapThresholds.gapThresholdNs(processPeriodNs ?: frameIntervalNs),
        longGapNs: Long = GapThresholds.longGapThresholdNs(processPeriodNs ?: frameIntervalNs),
        /** fps unset (E2 1장): no expected interval at the start; the aggregator learns the diagnostic one from the warm-up. */
        learnFromWarmup: Boolean = false,
    ) {
        val startMonoMs: Long = (startRaw + frameOffsetNs) / 1_000_000L
        val agg = FeatureAggregator(
            startMonoMs, Synth.UTC0, gapThresholdNs = gapNs, longGapThresholdNs = longGapNs, sessionStartRawNs = startRaw,
            expectedIntervalNs = processPeriodNs ?: frameIntervalNs, learnThresholdsFromWarmup = learnFromWarmup,
        )
        val scheduler = FrameScheduler(sink(agg), processPeriodNs, frameIntervalNs)
        val filledRaw = ArrayList<Long>()
        var started = false

        fun cr(raw: Long) = CameraStamp(raw, raw + crOffsetNs)
        fun fr(raw: Long) = CameraStamp(raw, raw + frameOffsetNs)

        fun captureResult(raw: Long): FrameScheduler.CaptureDecision = scheduler.onCaptureResult(cr(raw))

        /** An analyzer frame; [face] = Face succeeds, else a Face inference error. Returns the scheduler's outcome. */
        fun frame(raw: Long, face: Boolean = true, faceInferMs: Double = 15.0): FrameScheduler.FrameOutcome {
            val st = fr(raw)
            if (!started) {
                started = true
                agg.onScene(SceneSample(st.captureMonoNs, 118.0, 4.0, 9.0, rawSensorTs = raw))
                scheduler.onSessionStart(st)
            }
            val out = scheduler.onFrameReceived(st)
            when (out) {
                FrameScheduler.FrameOutcome.SLOT -> {
                    if (face) {
                        scheduler.onFaceSucceeded(st)
                        filledRaw.add(raw)
                        agg.onFrameProcessed(ProcessedFrame(st.captureMonoNs, faceInferMs, FrameSample(st.captureMonoNs, 1_000_000L, false, rawSensorTs = raw), rawSensorTs = raw))
                    } else {
                        scheduler.onFaceInferenceError(st)
                    }
                }
                FrameScheduler.FrameOutcome.NOT_SLOT -> scheduler.onFrameSkipped(st)
                FrameScheduler.FrameOutcome.OUT_OF_ORDER -> scheduler.onPreFaceError(st)
                FrameScheduler.FrameOutcome.AFTER_FENCE -> Unit
            }
            return out
        }

        /** The normal path of one captured frame: capture result then its analyzer frame. */
        fun both(raw: Long, face: Boolean = true) {
            captureResult(raw)
            frame(raw, face)
        }

        fun closeAll(nowMonoMs: Long) = agg.closeBuckets(nowMonoMs, device)

        /** The normal stop order with a clean drain, as [StopSequence] runs it. */
        fun stop(fenceRaw: Long, captureResultsDrained: Boolean = true, queueDrained: Boolean = true): StopResult = StopSequence(
            stopInputs = { fenceRaw / 1_000_000L },
            raiseFence = { f -> scheduler.fence(fenceRaw); agg.stopInputs(f, fenceRaw) },
            drainCaptureResults = { captureResultsDrained },
            awaitAnalysisIdle = { 0L },
            closeSlotScheduler = { scheduler.close() },
            closePoseSlot = { },
            awaitPoseIdle = { 0L },
            drainAggregationQueue = { queueDrained },
            finish = { f -> StopFinalizer.finish(agg, f, startMonoMs, Synth.UTC0, device, SessionEndReason.USER) },
            writeEnd = { },
        ).run()
    }

    /** A 0.2.4 header with a fixed [24,24] request, so the summary's first line is about the condition under test only. */
    private fun fixedHeader(preset: String, schedule: FaceSchedule, periodNs: Long, startMonoMs: Long): SessionHeader = Synth.header.copy(
        tStartMonoMs = startMonoMs, capturePreset = preset, cameraFpsRequestLower = 24, cameraFpsRequestUpper = 24, cameraFpsRangesSupported = "[24,24],[30,30]", nominalFps = 24,
        faceSchedule = schedule, faceProcessPeriodNs = periodNs, frameGapThresholdNs = GapThresholds.gapThresholdNs(periodNs), frameLongGapThresholdNs = GapThresholds.longGapThresholdNs(periodNs),
    )

    private val checkedStop = StopSummary(checked = true, captureResultDrainComplete = true, aggregationQueueDrained = true)

    private fun stream(fps: Double, seconds: Double, startRaw: Long = 5_000_000_000L): List<Long> {
        val n = (fps * seconds).toInt()
        val interval = 1e9 / fps
        return (0 until n).map { startRaw + (it * interval).roundToLong() }
    }

    // ---- (a) 24.000 fps → 15 Hz, long run: filled ≈ 15 Hz, intervals are 41.7 / 83.3 only

    @Test
    fun a_twentyFourFpsToFifteenHzFillsAtFifteenHzWithOnlyOneAndTwoFrameIntervals() {
        val raws = stream(24.0, 600.0) // 10 minutes, 14 400 frames
        val s = Session(raws[0], period15, frame24)
        for (r in raws) s.both(r)
        val filled = s.filledRaw
        val spanS = (filled.last() - filled.first()) / 1e9
        val rate = (filled.size - 1) / spanS
        assertTrue(abs(rate - 15.0) < 0.02, "filled rate $rate Hz")
        val intervals = filled.zipWithNext { a, b -> b - a }.map { (it / 1e5).roundToLong() / 10.0 }.toSet() // 0.1 ms resolution
        assertEquals(setOf(41.7, 83.3), intervals, "only one-frame and two-frame intervals occur")
        assertEquals(0L, s.scheduler.slotsMissed)
        assertEquals(s.scheduler.slotsExpected, s.scheduler.slotsFilled)
        assertEquals(listOf(0.0, 83.3, 125.0, 208.3, 250.0, 333.3), filled.take(6).map { ((it - raws[0]) / 1e5).roundToLong() / 10.0 }, "directive E 3장 example phase")
        val t = s.agg.totals
        assertEquals(t.processingSlotsExpected, t.processingSlotsFilled + t.processingSlotsMissed)
        assertEquals(raws.size.toLong(), t.framesRequested)
        assertEquals(t.framesRequested - t.framesProcessed, t.framesSkippedIntentional)
        assertEquals(emptyList(), CounterConsistency.check(t))
    }

    // ---- (b) 23.98 fps → 15 Hz, 8 minutes, no loss: missed = 0

    @Test
    fun b_realCadenceTwentyThreePointNinetyEightToFifteenHzForEightMinutesMissesNothing() {
        val raws = stream(23.98, 480.0)
        val s = Session(raws[0], period15, frame24)
        for (r in raws) s.both(r)
        assertEquals(0L, s.scheduler.slotsMissed)
