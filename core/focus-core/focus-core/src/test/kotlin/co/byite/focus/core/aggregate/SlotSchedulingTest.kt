    // ---- (g) two processing opportunities captured before the fence never reach the analyzer: expected +2, missed +2

    @Test
    fun g_slotsLostToBackpressureBeforeTheFenceAreExpectedAndMissed() {
        val raws = stream(24.0, 2.0)
        val s = Session(raws[0], period15, frame24)
        for (r in raws) s.both(r)
        val e0 = s.agg.totals.processingSlotsExpected
        // later frames are captured (capture results arrive) but KEEP_ONLY_LATEST drops their images: feed until two slots opened
        var raw = raws.last()
        var fed = 0
        var selected = 0
        while (selected < 2) {
            raw += frame24
            fed++
            if (s.captureResult(raw) == FrameScheduler.CaptureDecision.SELECTED) selected++
        }
        assertTrue(fed in 2..4, "two slots need 2–4 frames at 15 Hz on 24 fps, fed $fed")
        val fenceRaw = raw + frame24 / 2
        s.scheduler.fence(fenceRaw)
        s.agg.stopInputs((fenceRaw) / 1_000_000L, fenceRaw)
        assertEquals(2L, s.scheduler.close(), "CLOSE terminates both open slots as missed")
        val t = s.agg.totals
        assertEquals(e0 + 2, t.processingSlotsExpected)
        assertEquals(2L, t.processingSlotsMissed)
        assertEquals(e0, t.processingSlotsFilled)
        assertEquals(fed.toLong(), t.backpressureDrops, "every capture result without an analyzer frame")
        assertEquals(emptyList(), CounterConsistency.check(t))
        // the same loss noticed by a later frame instead of CLOSE: missed by backpressure
        val s3 = Session(raws[0], period15, frame24)
        for (r in raws) s3.both(r)
        var lost = raws.last()
        do { lost += frame24 } while (s3.captureResult(lost) != FrameScheduler.CaptureDecision.SELECTED)
        s3.frame(lost + 2 * frame24)
        assertEquals(1L, s3.scheduler.slotsMissedByBackpressure)
        assertEquals(1L, s3.agg.totals.processingSlotsMissed)
    }

