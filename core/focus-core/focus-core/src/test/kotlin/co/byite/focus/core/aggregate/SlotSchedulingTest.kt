        assertEquals(s.agg.totals.processingSlotsExpected, s.agg.totals.processingSlotsFilled)
        val rate = (s.filledRaw.size - 1) / ((s.filledRaw.last() - s.filledRaw.first()) / 1e9)
        assertTrue(abs(rate - 15.0) < 0.02, "filled rate $rate Hz")
        // the phase never accumulates: every selected frame lies within half a (real) frame interval of a slot target
        val anchor = s.scheduler.anchorRawTs!!
        val halfReal = (1e9 / 23.98 / 2).roundToLong() + 100_000L
        for (f in s.filledRaw) {
            val phase = (f - anchor) % period15
            val dist = minOf(phase, period15 - phase)
            assertTrue(dist <= halfReal, "frame $f is ${dist / 1e6} ms from a slot target")
        }
        assertEquals(emptyList(), CounterConsistency.check(s.agg.totals))
    }

